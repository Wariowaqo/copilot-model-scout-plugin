// Bundles the widget into one self-contained HTML file (inline CSS and JS, no external
// requests), then writes:
//   src/generated/widget-html.ts  - imported by the Worker and served as the ui:// resource
//   dist/widget.html              - the same HTML, for inspection
//   dist/harness.html             - the widget with sample data, to view in a browser
import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const p = (...s) => join(root, ...s);

const result = await build({
  entryPoints: [p("src/widget/main.ts")],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "none",
  logLevel: "warning",
});
const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const css = (await readFile(p("src/widget/styles.css"), "utf8")).replace(/<\/style/gi, "<\\/style");
const template = await readFile(p("src/widget/index.html"), "utf8");

const fill = (demo) =>
  template
    .replace("/*__STYLE__*/", () => css)
    .replace("/*__SCRIPT__*/", () => js)
    .replace("<!--__DEMO__-->", () => demo);

const html = fill("");
await mkdir(p("src/generated"), { recursive: true });
await mkdir(p("dist"), { recursive: true });
await writeFile(
  p("src/generated/widget-html.ts"),
  `// Generated by scripts/build-widget.mjs. Do not edit.\nexport const WIDGET_HTML = ${JSON.stringify(html)};\n`,
);
await writeFile(p("dist/widget.html"), html);

const sample = await readFile(p("test/fixtures/sample-payload.json"), "utf8");
const harness = fill(
  `<script>(function(){var q=new URLSearchParams(location.search);var d=${sample.replace(/</g, "\\u003c")};` +
    `var v=q.get("view");if(v==="card"){d.view="card";d.models=d.models.slice(0,1);}` +
    `window.__MODEL_SCOUT_DEMO__={payload:d,theme:q.get("theme")==="dark"?"dark":q.get("theme")==="light"?"light":undefined};})();</script>`,
);
await writeFile(p("dist/harness.html"), harness);

console.log(`widget: ${(html.length / 1024).toFixed(1)} KB`);
